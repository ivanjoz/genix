// The PCGE chart of accounts every movement is classified into, so its journal entry balances.
//
// Supplies, purchase lines, expenses and assets all pick an account from it, and the accounting
// pages read it, so it lives in core. Mirrors backend/accounting/types/pcge.go; the arrays below
// are generated from there — run `go run ./scripts sync_struct_interfaces` after changing them.

export interface IPCGEAccount {
  code: number
  name: string
  // A leaf: the only kind of account a line may be posted to. Parents just group their children.
  postable?: boolean
  // On a 60x purchase account: the stock account its reception debits, and the 61x it credits.
  stockCode?: number
  variationCode?: number
  // On a 33x asset account: the 39x credited and the 68x debited each month it depreciates.
  accumulatedDepreciationCode?: number
  depreciationExpenseCode?: number
}

export interface IPCGEKindPrefix {
  kind: number
  prefix: number
}

