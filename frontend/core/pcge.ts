const pcgeAccountsByCode = new Map(PCGE_ACCOUNTS.map(account => [account.code, account]))

export const findPCGEAccount = (code: number): IPCGEAccount | undefined => pcgeAccountsByCode.get(code)

// isPCGEAccountAllowed mirrors the backend's IsPCGEAccountAllowed: the account is a leaf and its
// code starts with one of the kind's prefixes. Compared on the digits, so prefix 33 admits 3369.
export const isPCGEAccountAllowed = (kind: number, code: number): boolean => {
  if (!pcgeAccountsByCode.get(code)?.postable) { return false }
  return PCGE_KIND_PREFIXES.some(kindPrefix => kindPrefix.kind === kind
    && String(code).startsWith(String(kindPrefix.prefix)))
}

// pcgeAccountsForKind is what a picker offers: every account the kind may use.
export const pcgeAccountsForKind = (kind: number): IPCGEAccount[] =>
  PCGE_ACCOUNTS.filter(account => isPCGEAccountAllowed(kind, account.code))

// pcgeAccountLabel names an account the way a user can tell it apart. Subaccount names repeat
// across the chart ("Edificaciones" is a rent, a maintenance, a depreciation…), so a 4+ digit
// account carries its parent's name too: "6352 · Alquileres — Edificaciones".
export const pcgeAccountLabel = (code: number): string => {
  const account = pcgeAccountsByCode.get(code)
  if (!account) { return String(code) }
  const parent = code >= 1000 ? pcgeAccountsByCode.get(Math.floor(code / 10)) : undefined
  return parent ? `${code} · ${parent.name} — ${account.name}` : `${code} · ${account.name}`
}
