// FindPlameCode returns the table 22 entry for a code, so a save handler can reject codes the
// PLAME file would refuse.
func FindPlameCode(code string) (PlameCodeOption, bool) {
	for _, option := range PlameCodeOptions {
		if option.Code == code {
			return option, true
		}
	}
	return PlameCodeOption{}, false
}
